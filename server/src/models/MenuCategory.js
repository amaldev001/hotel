import mongoose from 'mongoose';

const menuCategorySchema = new mongoose.Schema(
  {
    restaurantId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Restaurant',
      required: true,
    },
    name: {
      type: String,
      required: true,
      trim: true,
    },
    description: {
      type: String,
      default: '',
    },
    sortOrder: {
      type: Number,
      default: 0,
    },
    isActive: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  }
);

menuCategorySchema.index({ restaurantId: 1, isActive: 1 });

export const MenuCategory = mongoose.model('MenuCategory', menuCategorySchema);
export default MenuCategory;
